def _cumulative_co2(controller, scenario, seeds=(0, 1, 2, 3, 4), ef_by_hour=None, flat=False):
    """Per-seed cumulative-CO2 series (hourly resolution) from saved frames."""
    series = []
    for seed in seeds:
        path = MATRIX_ROOT / controller / scenario / f"seed{seed:02d}" / "telemetry.csv"
        frame = pd.read_csv(path).sort_values("timestamp").reset_index(drop=True)
        hours = pd.to_datetime(frame["timestamp"]).dt.hour.to_numpy()
        power = frame.groupby("timestamp")["power_kW"].sum()
        power = power.reindex(frame["timestamp"].drop_duplicates()).to_numpy()
        ef = (np.full_like(power, FLAT_EF, dtype=float) if flat
              else np.array([ef_by_hour[h] for h in hours], dtype=float))
        cum = np.cumsum(power / 60.0 * ef)
        series.append(cum[59::60])  # hour-end values, 24 points
    return np.asarray(series)


def fig_g4(scenario="weekday"):
    """G4: cumulative CO2 avoided (C3-C4) + flat-EF counterfactual line."""
    ef_by_hour = {h: ef for h, ef, _ in grid_mod.hourly_rows()}
    c3 = _cumulative_co2("c3", scenario, ef_by_hour=ef_by_hour)
    c4 = _cumulative_co2("c4-with", scenario, ef_by_hour=ef_by_hour)
    c4_flat = _cumulative_co2("c4-with", scenario, flat=True)
    hours = np.arange(1, 25)
    avoided = c3 - c4

    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    pd.DataFrame({
        "hour": hours,
        "c3_co2_mean": c3.mean(axis=0), "c3_co2_std": c3.std(axis=0, ddof=1),
        "c4_co2_mean": c4.mean(axis=0), "c4_co2_std": c4.std(axis=0, ddof=1),
        "avoided_mean": avoided.mean(axis=0), "avoided_std": avoided.std(axis=0, ddof=1),
        "c4_flat_mean": c4_flat.mean(axis=0),
    }).to_csv(TABLES_DIR / "g4_co2.csv", index=False)

    summary = pd.read_csv(MATRIX_SUMMARY)
    fig, ax = plt.subplots(figsize=(10, 5))
    ax.plot(hours, c3.mean(axis=0), label="C3 cumulative CO2 (hourly EF)", linewidth=2.0)
    ax.fill_between(hours, c3.mean(axis=0) - c3.std(axis=0, ddof=1),
                    c3.mean(axis=0) + c3.std(axis=0, ddof=1), alpha=0.2)
    ax.plot(hours, c4.mean(axis=0), label="C4-with cumulative CO2 (hourly EF)", linewidth=2.0)
    ax.fill_between(hours, c4.mean(axis=0) - c4.std(axis=0, ddof=1),
                    c4.mean(axis=0) + c4.std(axis=0, ddof=1), alpha=0.2)
    ax.plot(hours, c4_flat.mean(axis=0), "--",
            label="C4-with flat-EF counterfactual (0.710 every hour)")
    ax.fill_between(hours, c4.mean(axis=0), c3.mean(axis=0), alpha=0.15, label="CO2 avoided")
    ax.axvspan(*PEAK_SPAN, color="salmon", alpha=0.12)
    ax.set_xlabel("hour of day")
    ax.set_ylabel("cumulative CO2 [kg] (mean ± std, n=5)")
    ax.set_title(f"G4: cumulative CO2 avoided, C3 vs C4-with — {scenario}")
    ax.legend(fontsize=8)
    fig.text(0.01, 0.01, _comfort_footnote(summary, [scenario])
             + "; flat line proves the hourly series matters (Pitfall 6)", fontsize=7)
    fig.tight_layout()
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    out = FIG_DIR / "fig_g4_co2.png"
    fig.savefig(out, dpi=150)
    plt.close(fig)
    return out


def fig_g5(pred_csv):
    """G5: frozen-forecaster predicted-vs-actual (occupancy + demand panels)."""
    df = pd.read_csv(pred_csv)
    stats = []
    for (target, horizon), grp in df.groupby(["target", "horizon_min"]):
        err = grp["y_pred"].to_numpy() - grp["y_true"].to_numpy()
        stats.append({"target": target, "horizon_min": horizon, "n": len(grp),
                      "rmse": float(np.sqrt(np.mean(err ** 2))),
                      "mae": float(np.mean(np.abs(err)))})
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(stats).to_csv(TABLES_DIR / "g5_pred_actual_stats.csv", index=False)

    fig, axes = plt.subplots(1, 2, figsize=(12, 5))
    for ax, target in zip(axes, ("occupancy", "demand")):
        sub = df[df["target"] == target]
        if len(sub) > 2000:
            sub = sub.sample(2000, random_state=0)
        ax.scatter(sub["y_true"], sub["y_pred"], s=4, alpha=0.3)
        lims = [min(sub["y_true"].min(), sub["y_pred"].min()),
                max(sub["y_true"].max(), sub["y_pred"].max())]
        ax.plot(lims, lims, "r--", label="y=x")
        rmse = np.sqrt(np.mean((df[df['target'] == target]['y_pred']
                                - df[df['target'] == target]['y_true']) ** 2))
        ax.set_xlabel(f"actual {target}")
        ax.set_ylabel(f"predicted {target}")
        ax.set_title(f"{target} (RMSE={rmse:.3f}, n={len(df[df['target'] == target])})")
        ax.legend(fontsize=8)
    fig.suptitle("G5: frozen-forecaster predicted vs actual (holdout, horizons 30/60min)")
    fig.text(0.01, 0.01,
             "forecaster frozen (C1-trained HistGB, never retrained); comfort n/a — forecast quality gate",
             fontsize=7)
    fig.tight_layout()
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    out = FIG_DIR / "fig_g5_pred_actual.png"
    fig.savefig(out, dpi=150)
    plt.close(fig)
    return out


def fig_g6():
    """G6: two-panel ablations — forecast paired deltas + carbon premiums."""
    abl = pd.read_csv("results/ablation.csv")
    scenarios = [s for s in ("weekday", "weekend", "heatwave") if s in abl["scenario"].unique()]

    fc = abl[abl["panel"] == "forecast"]
    fc_agg = fc.groupby("scenario").agg(
        dE_mean=("d_energy_kwh", "mean"), dE_std=("d_energy_kwh", "std"),
        dCO2_mean=("d_co2_kg", "mean"), dCO2_std=("d_co2_kg", "std"),
        dComf_mean=("d_comfort_pp", "mean"), dComf_std=("d_comfort_pp", "std"))
    fc_agg.to_csv(TABLES_DIR / "g6_forecast_ablation.csv")

    carbon = abl[(abl["panel"] == "carbon") & (abl["ef_mode"] == "hourly")]
    prem = carbon.groupby(["scenario", "controller"]).agg(
        prem_mean=("co2_delta", "mean"), prem_std=("co2_delta", "std"))
    prem.reset_index().to_csv(TABLES_DIR / "g6_carbon_ablation.csv", index=False)

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))
    x = np.arange(len(scenarios))
    ax1.bar(x - 0.2, [fc_agg.loc[s, "dE_mean"] for s in scenarios], 0.4,
            yerr=[fc_agg.loc[s, "dE_std"] for s in scenarios], capsize=3,
            label="dEnergy kWh (C4-with − C4-as-C3)")
    ax1.bar(x + 0.2, [fc_agg.loc[s, "dCO2_mean"] for s in scenarios], 0.4,
            yerr=[fc_agg.loc[s, "dCO2_std"] for s in scenarios], capsize=3,
            label="dCO2 kg")
    ax1.axhline(0, color="k", linewidth=0.8)
    ax1.set_xticks(x)
    ax1.set_xticklabels(scenarios)
    ax1.set_ylabel("paired delta [mean ± std, n=5]")
    ax1.set_title("forecast ablation (negative = gain)")
    ax1.legend(fontsize=8)
    for i, s in enumerate(scenarios):
        ax1.text(i, ax1.get_ylim()[0], f"dComf {fc_agg.loc[s, 'dComf_mean']:+.1f}pp",
                 ha="center", va="bottom", fontsize=7)

    ctrls = ["c1", "c2", "c3", "c4-with"]
    w = 0.18
    sc = "weekday"
    for i, c in enumerate(ctrls):
        means = [prem.loc[(s, c), "prem_mean"] for s in [sc]]
        stds = [prem.loc[(s, c), "prem_std"] for s in [sc]]
        ax2.bar(np.arange(1) + (i - 1.5) * w, means, w, yerr=stds, capsize=3, label=c)
    ax2.axhline(0, color="k", linewidth=0.8)
    ax2.set_xticks([0])
    ax2.set_xticklabels([f"{sc}"])
    ax2.set_ylabel("load-shape premium [kg, hourly − flat; mean ± std]")
    ax2.set_title("carbon ablation (negative = load already in solar dip)")
    ax2.legend(fontsize=8)
    fig.suptitle("G6: ablations — forecasting buys kWh; CO2 win is less energy, not moved energy")
    fig.tight_layout()
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    out = FIG_DIR / "fig_g6_ablation.png"
    fig.savefig(out, dpi=150)
    plt.close(fig)
    return out
