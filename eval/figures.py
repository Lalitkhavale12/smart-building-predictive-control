PEAK_SPAN = (18, 22)  # D-05 peak window 18:00-22:00
SOLAR_SPAN = (10, 16)  # EF solar dip 10-16h
G2_SCENARIOS = ["weekday", "weekend", "heatwave"]  # exam-day excluded: stub=weekday
FLAT_EF = grid_mod.GRID_EF_BASE_KG_PER_KWH


def _comfort_footnote(summary, scenarios):
    """One-line comfort context for figure footnotes (T-05-08)."""
    bits = []
    for sc in scenarios:
        sub = summary[summary["scenario"] == sc]
        if len(sub):
            c3 = sub[sub["controller"] == "c3"]
            c4 = sub[sub["controller"] == "c4-with"]
            if len(c3) and len(c4):
                bits.append(
                    f"{sc}: comfort C3 {c3['comfort_pct_mean'].iloc[0]:.1f}% "
                    f"vs C4 {c4['comfort_pct_mean'].iloc[0]:.1f}% (n=5, locked 22-26C)"
                )
    return "; ".join(bits)


def _per_seed_hourly(controller, scenario, seeds=(0, 1, 2, 3, 4)):
    """Per-seed hourly-mean total-kW + occupancy series from saved frames."""
    kw, occ = {}, {}
    for seed in seeds:
        path = MATRIX_ROOT / controller / scenario / f"seed{seed:02d}" / "telemetry.csv"
        frame = pd.read_csv(path)
        frame["hour"] = pd.to_datetime(frame["timestamp"]).dt.hour
        per_min = frame.groupby("timestamp").agg({"power_kW": "sum", "occupancy": "sum"})
        per_min["hour"] = pd.to_datetime(per_min.index).hour
        kw[seed] = per_min.groupby("hour")["power_kW"].mean()
        occ[seed] = per_min.groupby("hour")["occupancy"].mean()
    return pd.DataFrame(kw), pd.DataFrame(occ)


def fig_g1(scenario="weekday"):
    """G1: 24h energy profile C3 vs C4-with + occupancy shade + peak/solar shade."""
    summary = pd.read_csv(MATRIX_SUMMARY)
    c3 = _per_seed_hourly("c3", scenario)[0]
    c4 = _per_seed_hourly("c4-with", scenario)[0]
    occ = _per_seed_hourly("c3", scenario)[1]
    hours = c3.index.to_numpy(dtype=float) + 0.5

    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    pd.DataFrame({
        "hour": c3.index.to_numpy(),
        "c3_kw_mean": c3.mean(axis=1).to_numpy(),
        "c3_kw_std": c3.std(axis=1, ddof=1).to_numpy(),
        "c4_kw_mean": c4.mean(axis=1).to_numpy(),
        "c4_kw_std": c4.std(axis=1, ddof=1).to_numpy(),
        "occupancy_mean": occ.mean(axis=1).to_numpy(),
    }).to_csv(TABLES_DIR / "g1_24h_profile.csv", index=False)

    fig, ax = plt.subplots(figsize=(10, 5))
    ax.axvspan(*PEAK_SPAN, color="salmon", alpha=0.18, label="peak 18-22h (ToU +Rs1.10)")
    ax.axvspan(*SOLAR_SPAN, color="gold", alpha=0.15, label="solar dip 10-16h (EF x0.80)")
    ax.plot(hours, c3.mean(axis=1), label="C3 (setback)", linewidth=2.0)
    ax.fill_between(hours, c3.mean(axis=1) - c3.std(axis=1, ddof=1),
                    c3.mean(axis=1) + c3.std(axis=1, ddof=1), alpha=0.2)
    ax.plot(hours, c4.mean(axis=1), label="C4-with (predictive)", linewidth=2.0)
    ax.fill_between(hours, c4.mean(axis=1) - c4.std(axis=1, ddof=1),
                    c4.mean(axis=1) + c4.std(axis=1, ddof=1), alpha=0.2)
    ax2 = ax.twinx()
    ax2.fill_between(hours, occ.mean(axis=1), color="lightgray", alpha=0.5,
                     step="mid", label="occupancy (persons)")
    ax.set_xlabel("hour of day")
    ax.set_ylabel("total building power [kW] (hourly mean ± std, n=5)")
    ax2.set_ylabel("total occupancy [persons]")
    ax.set_title(f"G1: 24h load shape C3 vs C4-with — {scenario} (kWh moved out of peak visible)")
    ax.set_xlim(0, 24)
    h1, l1 = ax.get_legend_handles_labels()
    h2, l2 = ax2.get_legend_handles_labels()
    ax.legend(h1 + h2, l1 + l2, loc="upper right", fontsize=8)
    fig.text(0.01, 0.01, _comfort_footnote(summary, [scenario]), fontsize=7)
    fig.tight_layout()
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    out = FIG_DIR / "fig_g1_24h_profile.png"
    fig.savefig(out, dpi=150)
    plt.close(fig)
    return out


