def _pareto_points():
    """Weekday (energy, comfort) mean±std for matrix controllers + sweep configs."""
    summary = pd.read_csv(MATRIX_SUMMARY)
    pts = []
    for c in ("c1", "c2", "c3", "c4-as-c3", "c4-with"):
        row = summary[(summary["scenario"] == "weekday") & (summary["controller"] == c)]
        pts.append({"label": ("tuned-C4" if c == "c4-with"
                              else ("stock-C4" if c == "c4-as-c3" else c.upper())),
                    "energy": row["energy_kwh_mean"].iloc[0],
                    "energy_std": row["energy_kwh_std"].iloc[0],
                    "comfort": row["comfort_pct_mean"].iloc[0],
                    "comfort_std": row["comfort_pct_std"].iloc[0],
                    "kind": "matrix"})
    sweep = pd.read_csv("results/tuning_sweep.csv")
    sw = sweep[sweep["scenario"] == "weekday"]
    for name, grp in sw.groupby("config"):
        pts.append({"label": f"sweep:{name}",
                    "energy": grp["energy_kwh"].mean(),
                    "energy_std": grp["energy_kwh"].std(ddof=1),
                    "comfort": grp["comfort_pct"].mean(),
                    "comfort_std": grp["comfort_pct"].std(ddof=1),
                    "kind": "sweep"})
    # H6: ±1C band recompute adds vertical spread (same energy, new comfort).
    band = pd.read_csv("results/tuning_sweep_band.csv")
    band_wd = band[band["scenario"] == "weekday"]
    band_energy = {r["label"]: r["energy"] for r in pts if r["label"].startswith("sweep:")}
    band_energy.update({("sweep:stock" if k == "stock" else k): v
                        for k, v in band_energy.items()})
    for _, r in band_wd.iterrows():
        key = f"sweep:{r['config']}"
        if key in band_energy and r["band"] != "locked22-26":
            pts.append({"label": f"{key}@{r['band']}",
                        "energy": band_energy[key],
                        "energy_std": 0.0,
                        "comfort": r["comfort_pct"],
                        "comfort_std": 0.0,
                        "kind": "band"})
    return pd.DataFrame(pts)


